"""Run candidate code in a separate process and cache the results.

This is process isolation with a timeout, not a security sandbox. In the
offline simulator every candidate is generated by this repo, so that is enough.
If you plug in real LLM-written code (llm.py), run it inside a container.
"""
from __future__ import annotations

import atexit
import hashlib
import json
import subprocess
import sys
from pathlib import Path

_RUNNER = r'''
import sys, json, signal
def main():
    req = json.load(sys.stdin)
    def handler(signum, frame):
        raise TimeoutError()
    signal.signal(signal.SIGALRM, handler)
    allres = []
    for source in req["sources"]:
        ns = {}
        try:
            exec(compile(source, "<cand>", "exec"), ns)
            fn = ns[req["entry"]]
        except BaseException:
            allres.append([{"e": "LoadError"}] * len(req["inputs"]))
            continue
        results, dead = [], False
        for args in req["inputs"]:
            if dead:
                results.append({"e": "Timeout"})
                continue
            signal.setitimer(signal.ITIMER_REAL, 0.5)
            try:
                res = fn(*json.loads(json.dumps(args)))
                results.append({"v": json.loads(json.dumps(res))})
            except TimeoutError:
                results.append({"e": "Timeout"})
                dead = True
            except BaseException as e:
                results.append({"e": type(e).__name__})
            finally:
                signal.setitimer(signal.ITIMER_REAL, 0)
        allres.append(results)
    print("@@RESULT@@" + json.dumps(allres))
main()
'''

_CACHE_FILE = Path(".cache") / "sandbox-v2.json"
_cache: dict[str, list] | None = None
_dirty = False


def _load() -> dict:
    global _cache
    if _cache is None:
        try:
            _cache = json.loads(_CACHE_FILE.read_text())
        except Exception:
            _cache = {}
    return _cache


def _flush() -> None:
    if _dirty and _cache is not None:
        _CACHE_FILE.parent.mkdir(exist_ok=True)
        _CACHE_FILE.write_text(json.dumps(_cache))


atexit.register(_flush)


def run_many(sources: list[str], entry: str, inputs: list, timeout: int = 300) -> list[list[dict]]:
    """Call `entry` of each source on every input. One result list per source,
    each item {"v": value} or {"e": ErrName}. A source that times out once is
    abandoned (its remaining inputs are marked Timeout)."""
    global _dirty
    cache = _load()
    keys = [hashlib.sha256(json.dumps([s, entry, inputs], sort_keys=True).encode()).hexdigest() for s in sources]
    todo = [i for i, k in enumerate(keys) if k not in cache]
    if todo:
        try:
            proc = subprocess.run(
                [sys.executable, "-I", "-c", _RUNNER],
                input=json.dumps({"sources": [sources[i] for i in todo], "entry": entry, "inputs": inputs}),
                capture_output=True, text=True, timeout=timeout,
            )
            line = [l for l in proc.stdout.splitlines() if l.startswith("@@RESULT@@")]
            res = json.loads(line[-1][len("@@RESULT@@"):])
        except Exception:
            res = [[{"e": "RunnerError"}] * len(inputs) for _ in todo]
        for i, r in zip(todo, res):
            cache[keys[i]] = r
        _dirty = True
    return [cache[k] for k in keys]


def run_function(source: str, entry: str, inputs: list) -> list[dict]:
    return run_many([source], entry, inputs)[0]
